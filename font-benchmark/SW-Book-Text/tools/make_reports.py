"""Generate machine-readable coverage + provenance reports from the built fonts.

    python3 tools/make_reports.py
"""
import os, sys, json, hashlib, platform, importlib.metadata as md, unicodedata
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REP = os.path.join(ROOT, "reports")
GROUPS = {
    "hebrew_base_letters_22": [c for c in range(0x05D0, 0x05EB) if c not in (0x05DA, 0x05DD, 0x05DF, 0x05E3, 0x05E5)],
    "hebrew_final_forms_5": [0x05DA, 0x05DD, 0x05DF, 0x05E3, 0x05E5],
    "hebrew_punctuation": [0x05BE, 0x05F3, 0x05F4, 0x05C0, 0x05C3],
    "hebrew_points_and_dagesh": [0x05B0, 0x05B1, 0x05B2, 0x05B3, 0x05B4, 0x05B5, 0x05B6, 0x05B7, 0x05B8, 0x05B9,
                                 0x05BA, 0x05BB, 0x05BC, 0x05BD, 0x05BF, 0x05C1, 0x05C2, 0x05C7],
    "digits_0_9": list(range(0x30, 0x3A)),
    "latin_uppercase": list(range(0x41, 0x5B)),
    "latin_lowercase": list(range(0x61, 0x7B)),
    "ascii_punctuation_symbols": [c for c in range(0x21, 0x7F) if not chr(c).isalnum()],
    "extended_punctuation_symbols": [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x201E, 0x2026, 0x2022, 0xAB, 0xBB,
                                     0xB7, 0xA7, 0xB6, 0xB0, 0xA9, 0xB1, 0xD7, 0xF7, 0x2212, 0x20AA],
    "spaces_and_controls": [0x20, 0xA0, 0x200C, 0x200D, 0x200E, 0x200F],
}


def coverage(path):
    f = TTFont(path)
    cmap = f.getBestCmap()
    out = {"file": os.path.relpath(path, ROOT), "sha256": hashlib.sha256(open(path, "rb").read()).hexdigest(),
           "glyph_count": len(f.getGlyphOrder()), "cmap_codepoints": len(cmap), "groups": {}}
    missing_all = []
    for g, cps in GROUPS.items():
        present = [c for c in cps if c in cmap]
        miss = [c for c in cps if c not in cmap]
        missing_all += miss
        out["groups"][g] = {
            "required": len(cps), "present": len(present),
            "missing": ["U+%04X" % c for c in miss],
            "glyphs": {"U+%04X" % c: {"char": chr(c), "name": unicodedata.name(chr(c), "?"), "glyph": cmap[c]}
                       for c in present},
        }
    out["all_required_present"] = not missing_all
    out["hebrew_letterforms_total"] = (out["groups"]["hebrew_base_letters_22"]["present"]
                                       + out["groups"]["hebrew_final_forms_5"]["present"])
    feats = sorted({fr.FeatureTag for fr in f["GPOS"].table.FeatureList.FeatureRecord})
    out["gpos_features"] = feats
    out["tables"] = sorted(t for t in f.keys() if t != "GlyphOrder")
    return out


def main():
    rep = {"generated_by": "tools/make_reports.py", "fonts": {}}
    for w in ("Regular", "Bold"):
        rep["fonts"][w] = coverage(os.path.join(ROOT, "fonts", "SWBookText-%s.ttf" % w))
    with open(os.path.join(REP, "glyph_coverage.json"), "w", encoding="utf-8") as fh:
        json.dump(rep, fh, indent=1, ensure_ascii=False)
    # specimen text hash
    h = hashlib.sha256(open(os.path.join(ROOT, "specimen", "texts.py"), "rb").read()).hexdigest()
    open(os.path.join(REP, "specimen_text.sha256"), "w").write("%s  specimen/texts.py\n" % h)
    # provenance
    prov = json.load(open(os.path.join(REP, "provenance_glyphs.json"), encoding="utf-8"))
    deps = {}
    for pkg in ("fonttools", "ufoLib2", "ufo2ft", "skia-pathops", "uharfbuzz", "fontbakery", "pypdf", "pypdfium2",
                "freetype-py", "opentype-sanitizer", "numpy", "pillow", "pytest", "booleanOperations", "cu2qu"):
        try:
            deps[pkg] = md.version(pkg)
        except md.PackageNotFoundError:
            pass
    reg = [p for p in prov if p["weight"] == "Regular"]
    by_method = {}
    for p in reg:
        by_method.setdefault(p["construction"], []).append(p["glyph"])
    meta = {
        "python": platform.python_version(), "platform": platform.platform(),
        "dependencies": deps,
        "third_party_assets": [],
        "third_party_font_files_read_during_build": [],
        "statement": ("Every outline is generated by the scripts in src/swbook from hand-written centre-lines, "
                      "polygons and an elliptical-pen stroke model. No font binary is opened by the build "
                      "(verified by tests/test_font.py::test_build_reads_no_foreign_font_binaries). "
                      "This is evidence of process, not a legal opinion: no claim of legal independence or copyright "
                      "protection is made; legal review is required."),
        "glyph_construction_methods": {k: {"count": len(v), "glyphs": v} for k, v in by_method.items()},
        "sources_sha256": {fn: hashlib.sha256(open(os.path.join(ROOT, "src", "swbook", fn), "rb").read()).hexdigest()
                           for fn in sorted(os.listdir(os.path.join(ROOT, "src", "swbook"))) if fn.endswith(".py")},
    }
    with open(os.path.join(REP, "provenance_summary.json"), "w", encoding="utf-8") as fh:
        json.dump(meta, fh, indent=1, ensure_ascii=False)
    print("reports written to", REP)


if __name__ == "__main__":
    main()
